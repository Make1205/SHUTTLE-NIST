#!/usr/bin/env python3
"""Generate the 93-bit reverse-CDT tables used by sampler.c.

For each mode, the small sampler has the exact rational standard deviation
sigma/64. Entry i is the nearest integer to

    2^93 * Pr[X >= i + 1],  X <- D_{Z^+, small_sigma}.

The output is split into three little-endian 31-bit limbs. Only Python's
standard-library Decimal arithmetic is used, so generation is deterministic.
"""

from decimal import Decimal, ROUND_DOWN, ROUND_HALF_EVEN, getcontext
from pathlib import Path
from typing import List, Tuple

getcontext().prec = 300

MODES = (
    (120, 70, 12),
    (180, 82, 14),
    (255, 99, 17),
)

PRECISION_BITS = 93
LIMB_BITS = 31


def weights(sigma: Decimal, length: int) -> List[Decimal]:
    """Return enough nonnegative Gaussian weights for a negligible tail."""
    out = []
    k = 0
    cutoff = Decimal(2) ** Decimal(-220)
    while k <= length or not out or out[-1] > cutoff:
        x = Decimal(k)
        out.append((-(x * x) / (Decimal(2) * sigma * sigma)).exp())
        k += 1
    return out


def thresholds(wide_sigma: int, length: int) -> List[int]:
    sigma = Decimal(wide_sigma) / Decimal(64)
    ws = weights(sigma, length)
    normalizer = sum(ws)
    scale = Decimal(1 << PRECISION_BITS)
    return [
        int((sum(ws[i + 1 :]) * scale / normalizer).quantize(
            Decimal(1), rounding=ROUND_HALF_EVEN
        ))
        for i in range(length)
    ]


def limbs(value: int) -> Tuple[int, int, int]:
    mask = (1 << LIMB_BITS) - 1
    return value & mask, (value >> LIMB_BITS) & mask, value >> (2 * LIMB_BITS)


def generate() -> str:
    lines = [
        "/*",
        " * rcdt_tables.h - 93-bit reverse-CDT tables.",
        " *",
        " * AUTO-GENERATED by gen_rcdt_tables.py. DO NOT EDIT BY HAND.",
        " */",
        "",
        "#ifndef SHUTTLE_RCDT_TABLES_H",
        "#define SHUTTLE_RCDT_TABLES_H",
        "",
        '#include "config.h"',
        '#include "params.h"',
        "",
    ]
    for index, (mode, sigma, length) in enumerate(MODES):
        small_sigma = Decimal(sigma) / Decimal(64)
        assert int((Decimal(11) * small_sigma).to_integral_value(
            rounding=ROUND_DOWN
        )) == length
        directive = "#if" if index == 0 else "#elif"
        lines.extend(
            [
                f"{directive} SHUTTLE_SIGMA == {sigma}",
                f"/* SHUTTLE-NIST-{mode}: small_sigma = {small_sigma}, "
                f"{length} entries. */",
                "static const uint32_t RCDT_3x31[RCDT_ENTRIES][3] = {",
            ]
        )
        values = thresholds(sigma, length)
        assert all(0 < value < (1 << PRECISION_BITS) for value in values)
        assert all(a > b for a, b in zip(values, values[1:]))
        for i, value in enumerate(values):
            lo, mid, hi = limbs(value)
            comma = "," if i + 1 < len(values) else ""
            lines.append(
                f"    {{0x{lo:08X}U, 0x{mid:08X}U, 0x{hi:08X}U}}{comma}"
            )
        lines.append("};")
    lines.extend(
        [
            "#else",
            '#  error "Unsupported SHUTTLE_SIGMA for RCDT table"',
            "#endif",
            "",
            "#endif /* SHUTTLE_RCDT_TABLES_H */",
            "",
        ]
    )
    return "\n".join(lines)


if __name__ == "__main__":
    output = Path(__file__).with_name("rcdt_tables.h")
    output.write_text(generate(), encoding="ascii")
    print(f"wrote {output}")
